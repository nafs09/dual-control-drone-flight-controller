/* ---- DWT cycle counter for µs timing --------------------- */
static void dwt_init() {
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0;
    DWT->CTRL  |= DWT_CTRL_CYCCNTENA_Msk;
}
static uint32_t dwt_us() {
    return DWT->CYCCNT / (FC_SYSCLK_HZ / 1000000UL);
}

/* ============================================================
 *  EXTI4 IRQ — IMU DRDY on PC4
 *  Keep absolutely minimal: no FP, no HAL, no mutex.
 * ============================================================ */
extern "C" void EXTI4_IRQHandler(void) {
    if (__HAL_GPIO_EXTI_GET_IT(IMU_DRDY_PIN)) {
        __HAL_GPIO_EXTI_CLEAR_IT(IMU_DRDY_PIN);
        g_state.imuDrdyCount++;
        /* osSemaphoreRelease is safe from ISR in FreeRTOS */
        osSemaphoreRelease(g_state.imuDrdySem);
    }
}

/* ============================================================
 *  USART2 RX IRQ — CRSF byte-by-byte receive
 * ============================================================ */
extern "C" void USART2_IRQHandler(void) {
    if (huart2.Instance->ISR & USART_ISR_RXNE) {
        uint8_t b = (uint8_t)huart2.Instance->RDR;
        g_crsf.feedByte(b);
    }
    HAL_UART_IRQHandler(&huart2);
}

extern "C" void USART1_IRQHandler(void) {
    HAL_UART_IRQHandler(&huart1);
}

/* ============================================================
 *  DSHOT TX/RX callbacks
 *  BUG FIX #PINS: Motor 3 = &huart3 (USART3/PB10)
 *                 Motor 4 = &huart6 (USART6/PC6)
 *                 No reference to huart7 (doesn't exist in LQFP64)
 * ============================================================ */
extern "C" void HAL_UART_TxCpltCallback(UART_HandleTypeDef* h) {
    if      (h == &huart4) Drivers::DShot::onTxComplete(0);
    else if (h == &huart5) Drivers::DShot::onTxComplete(1);
    else if (h == &huart3) Drivers::DShot::onTxComplete(2);
    else if (h == &huart6) Drivers::DShot::onTxComplete(3);
}
extern "C" void HAL_UART_RxCpltCallback(UART_HandleTypeDef* h) {
    if      (h == &huart4) Drivers::DShot::onRxComplete(0);
    else if (h == &huart5) Drivers::DShot::onRxComplete(1);
    else if (h == &huart3) Drivers::DShot::onRxComplete(2);
    else if (h == &huart6) {
        Drivers::DShot::onRxComplete(3);
        Drivers::DShot::updateAvgFreq();   /* After all 4 RX phases */
    } else if (h == &huart1) {
        gpsRxPushFromIsr(g_gpsRxByte);
        (void)HAL_UART_Receive_IT(&huart1, &g_gpsRxByte, 1);
    }
}

/* ============================================================
 *  CONTROL LOOP TASK  (~3840 Hz, IMU DRDY paced)
 * ============================================================ */
static void ControlLoopTask(void* /*arg*/) {
    osDelay(100);   /* Let sensors stabilise */
    g_mahony.reset(Quaternionf::identity());
    g_inekf.init({0,0,0}, {0,0,0}, Quaternionf::identity());

    uint32_t tPrev = dwt_us();

    for (;;) {
        /* Block until IMU DRDY — hardware-paced, no drift */
        osSemaphoreAcquire(g_state.imuDrdySem, osWaitForever);

        uint32_t tNow = dwt_us();
        float dt = (float)(tNow - tPrev) * 1e-6f;
        tPrev = tNow;
        if (dt <= 0.f || dt > 0.01f) dt = 1.f / CTRL_LOOP_HZ;

        uint32_t t0 = dwt_us();

        /* 1. Read IMU from hardware or the injected simulation sample. */
        Vector3f gyro, accel;
        bool imuSampleValid = true;
        if (Simulation::SimInterface::isSimulation()) {
            osMutexAcquire(g_state.imuMtx, osWaitForever);
            gyro = g_state.gyro_raw_rps; accel = g_state.accel_mps2;
            osMutexRelease(g_state.imuMtx);
        } else {
            imuSampleValid = g_imu.readRaw(gyro, accel);
        }
        if (!imuSampleValid) {
            osMutexAcquire(g_state.imuMtx, osWaitForever);
            g_state.imuReadError = true;
            osMutexRelease(g_state.imuMtx);
            osMutexAcquire(g_state.safetyMtx, osWaitForever);
            g_state.errorFlags |= FC_ERR_IMU;
            g_state.killMotors = true;
            osMutexRelease(g_state.safetyMtx);
            const uint16_t stop[4] = {0, 0, 0, 0};
            osMutexAcquire(g_state.motMtx, osWaitForever);
            for (int i = 0; i < 4; ++i) g_state.motorCmd[i] = stop[i];
            osMutexRelease(g_state.motMtx);
            if (Simulation::SimInterface::isSimulation())
                Simulation::SimInterface::exportMotors(stop);
            else if (g_dshotReady)
                Drivers::DShot::sendMotors(stop);
            g_state.ctrlLoopUs = dwt_us() - t0;
            continue;
        }
        /* 2. Mahony pre-computes a low-latency attitude from every IMU
         * sample. InvEKF consumes its attitude increment while estimating
         * the full navigation and calibration state. */
        static uint8_t ekfDecim = 0;
        Quaternionf att;
        Vector3f mahonyBias;
        osMutexAcquire(g_state.ahMtx, osWaitForever);
        g_mahony.updateIMU(gyro, accel, dt);
        att = g_mahony.getAttitude();
        mahonyBias = g_mahony.getGyroBias();
        osMutexRelease(g_state.ahMtx);

        bool predicted = false;
        Vector3f ekfGyroBias;
        osMutexAcquire(g_state.navMtx, osWaitForever);
        g_inekf.accumulateIMU(accel, gyro, att, dt);
        if (++ekfDecim >= 8) {
            ekfDecim = 0;
            g_inekf.predict(dt * 8.f);
            g_state.position_ned = g_inekf.getPosition();
            g_state.velocity_ned = g_inekf.getVelocity();
            ekfGyroBias = g_inekf.getGyroBias();
            predicted = true;
        }
        osMutexRelease(g_state.navMtx);

        if (predicted) {
            osMutexAcquire(g_state.ahMtx, osWaitForever);
            g_mahony.setGyroBias(ekfGyroBias);
            mahonyBias = g_mahony.getGyroBias();
            osMutexRelease(g_state.ahMtx);
        }
        osMutexAcquire(g_state.imuMtx, osWaitForever);
        g_state.imuReadError = false;
        g_state.gyro_raw_rps = gyro;
        g_state.gyro_rps = gyro - mahonyBias;
        g_state.accel_mps2 = accel;
        osMutexRelease(g_state.imuMtx);
        osMutexAcquire(g_state.ahMtx, osWaitForever);
        g_state.attitude  = att;
        g_state.euler_deg = att.toEulerRPY() * (180.f / 3.14159265f);
        osMutexRelease(g_state.ahMtx);

        /* 4. Flight mode FSM → control → motor commands */
        g_fsm.update(dt, g_inekf);

        /* 5. Send motor commands via DSHOT */
        osMutexAcquire(g_state.motMtx, osWaitForever);
        uint16_t cmds[4];
        for(int i=0;i<4;i++) cmds[i]=g_state.motorCmd[i];
        osMutexRelease(g_state.motMtx);
        if (Simulation::SimInterface::isSimulation())
            Simulation::SimInterface::exportMotors(cmds);
        else if (g_dshotReady)
            Drivers::DShot::sendMotors(cmds);

        g_state.ctrlLoopUs = dwt_us() - t0;
    }
}

/* ============================================================
 *  CRSF TASK (~500 Hz poll)
 * ============================================================ */
static void CRSFTask(void* /*arg*/) {
    for (;;) {
        osDelay(1); /* tick1ms() uses milliseconds; 2 ms doubled its timeout */
        bool fpv = (g_state.mode == FlightMode::FPV);
        g_crsf.processFrame(fpv);
        g_crsf.tick1ms();
    }
}

/* ============================================================
 *  BARO TASK (50 Hz)
 * ============================================================ */
static void BaroTask(void* /*arg*/) {
    osDelay(500);
    uint32_t lastGeneration = 0;
    for (;;) {
        osDelay(20);
        /* Driver work left: read MS5611 on SPI1 and publish altitude relative
         * to the navigation origin. This consumes any valid hardware/HIL feed. */
        osMutexAcquire(g_state.baroMtx, osWaitForever);
        const bool valid = g_state.baroValid;
        const uint32_t generation = g_state.baroGeneration;
        const float altitude = g_state.baro_alt_m;
        osMutexRelease(g_state.baroMtx);
        if (valid && generation != lastGeneration) {
            lastGeneration = generation;
            osMutexAcquire(g_state.navMtx, osWaitForever);
            g_inekf.updateBaro(altitude, 0.5f);
            g_state.position_ned = g_inekf.getPosition();
            g_state.velocity_ned = g_inekf.getVelocity();
            osMutexRelease(g_state.navMtx);
            syncMahonyGyroBiasFromInvEKF();
        }
    }
}

/* ============================================================
 *  MAG TASK (100 Hz)
 * ============================================================ */
static void MagTask(void* /*arg*/) {
    osDelay(200);
    uint32_t lastGeneration = 0;
    for (;;) {
        osDelay(10);
        /* Driver/calibration work left: read QMC5883L on I2C1, scale/soft-iron
         * calibrate it, and provide the local NED reference vector. */
        osMutexAcquire(g_state.magMtx, osWaitForever);
        const bool valid = g_state.magValid;
        const uint32_t generation = g_state.magGeneration;
        const Vector3f magBody = g_state.mag_body_uT;
        const Vector3f magNed = g_state.mag_reference_ned_uT;
        osMutexRelease(g_state.magMtx);
        if (valid && generation != lastGeneration) {
            lastGeneration = generation;
            osMutexAcquire(g_state.ahMtx, osWaitForever);
            if (magNed.norm() > 1.0e-3f) g_mahony.setMagReference(magNed);
            g_mahony.updateMag(magBody);
            osMutexRelease(g_state.ahMtx);
            osMutexAcquire(g_state.navMtx, osWaitForever);
            g_inekf.updateMag(magBody, magNed);
            osMutexRelease(g_state.navMtx);
            syncMahonyGyroBiasFromInvEKF();
        }
    }
}

/* ============================================================
 *  GPS TASK (10 Hz)
 * ============================================================ */
static void GPSTask(void* /*arg*/) {
    uint32_t lastSimGeneration = 0;
    uint32_t lastFixTick = 0;
    bool haveFix = false;
    bool latestFixValid = false;
    const auto setGpsError = [](bool fault) {
        osMutexAcquire(g_state.safetyMtx, osWaitForever);
        if (fault) g_state.errorFlags |= FC_ERR_GPS;
        else g_state.errorFlags &= ~FC_ERR_GPS;
        osMutexRelease(g_state.safetyMtx);
    };
    for (;;) {
        if (Simulation::SimInterface::isSimulation()) {
            osMutexAcquire(g_state.gpsMtx, osWaitForever);
            const bool valid = g_state.gps.fixValid;
            const uint32_t generation = g_state.gpsGeneration;
            const Vector3f simPos = g_state.sim_position_ned;
            const Vector3f simVel = g_state.sim_velocity_ned;
            osMutexRelease(g_state.gpsMtx);
            if (valid && generation != lastSimGeneration) {
                lastSimGeneration = generation;
                latestFixValid = true;
                haveFix = true;
                lastFixTick = osKernelGetTickCount();
                osMutexAcquire(g_state.navMtx, osWaitForever);
                g_inekf.updateGPS(simPos, simVel, 0.1f, 0.15f, 0.05f, 1.0f, 12);
                g_state.position_ned = g_inekf.getPosition();
                g_state.velocity_ned = g_inekf.getVelocity();
                osMutexRelease(g_state.navMtx);
                syncMahonyGyroBiasFromInvEKF();
            }
            const uint32_t now = osKernelGetTickCount();
            const bool stale = !haveFix || !latestFixValid ||
                static_cast<uint32_t>(now-lastFixTick) > 500u;
            if (stale) {
                osMutexAcquire(g_state.gpsMtx, osWaitForever);
                g_state.gps.fixValid = false;
                osMutexRelease(g_state.gpsMtx);
            }
            setGpsError(stale);
            osDelay(10);
            continue;
        }
        uint8_t byte;
        Communication::UBXParser::NavPvt fix;
        while (gpsRxPop(byte)) {
            if (!g_ubx.feed(byte, fix)) continue;

            GPSData gps;
            gps.lat_deg = fix.latitude_deg; gps.lon_deg = fix.longitude_deg;
            gps.alt_msl_m = fix.altitude_msl_m;
            gps.vel_n_mps = fix.velocity_n_mps;
            gps.vel_e_mps = fix.velocity_e_mps;
            gps.vel_d_mps = fix.velocity_d_mps;
            gps.hAcc_m = fix.horizontal_accuracy_m;
            gps.vAcc_m = fix.vertical_accuracy_m;
            gps.sAcc_mps = fix.speed_accuracy_mps;
            gps.positionDop = fix.position_dop;
            gps.numSats = fix.satellites;
            gps.fixValid = fix.fix_valid &&
                           g_inekf.gpsQualityAcceptable(gps.positionDop, gps.numSats);
            gps.lastUpdateMs = osKernelGetTickCount();
            latestFixValid = gps.fixValid;
            if (latestFixValid) {
                haveFix = true;
                lastFixTick = gps.lastUpdateMs;
            }

            NavOrigin origin = {};
            osMutexAcquire(g_state.gpsMtx, osWaitForever);
            g_state.gps = gps;
            ++g_state.gpsGeneration;
            if (!g_state.origin.set && gps.fixValid) {
                g_state.origin = {gps.lat_deg, gps.lon_deg, gps.alt_msl_m, true};
            }
            origin = g_state.origin;
            osMutexRelease(g_state.gpsMtx);

            if (gps.fixValid && origin.set) {
                constexpr double kEarthRadiusM = 6378137.0;
                constexpr double kDegToRad = 0.017453292519943295;
                const double lat0 = origin.lat_deg * kDegToRad;
                Vector3f pos_ned(
                    static_cast<float>((gps.lat_deg-origin.lat_deg)*kDegToRad*kEarthRadiusM),
                    static_cast<float>((gps.lon_deg-origin.lon_deg)*kDegToRad*kEarthRadiusM*std::cos(lat0)),
                    origin.alt_m-gps.alt_msl_m);
                Vector3f vel_ned(gps.vel_n_mps, gps.vel_e_mps, gps.vel_d_mps);
                osMutexAcquire(g_state.navMtx, osWaitForever);
                g_inekf.updateGPS(pos_ned, vel_ned, gps.hAcc_m, gps.vAcc_m,
                                  gps.sAcc_mps, gps.positionDop, gps.numSats);
                g_state.position_ned = g_inekf.getPosition();
                g_state.velocity_ned = g_inekf.getVelocity();
                osMutexRelease(g_state.navMtx);
                syncMahonyGyroBiasFromInvEKF();
                setGpsError(false);
            } else {
                setGpsError(true);
            }
        }
        const uint32_t now = osKernelGetTickCount();
        const bool stale = !haveFix || !latestFixValid ||
            static_cast<uint32_t>(now-lastFixTick) > 500u;
        if (stale) {
            osMutexAcquire(g_state.gpsMtx, osWaitForever);
            g_state.gps.fixValid = false;
            osMutexRelease(g_state.gpsMtx);
        }
        setGpsError(stale);
        osDelay(10);
    }
}

