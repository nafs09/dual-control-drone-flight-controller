/* ============================================================
 *  SYSTEM INIT — call from main() before osKernelStart()
 *
 *  BUG FIX #5: Original System_Init was truncated mid-function.
 *  All RTOS primitives, sensor init, and task creation happens here.
 * ============================================================ */
extern "C" void FC_SystemInit(void) {
    dwt_init();

    /* Shared state: creates all mutexes and semaphores */
    g_state.init();

    /* IMU */
    if (!g_imu.init(&hspi1)) {
        g_state.errorFlags |= FC_ERR_IMU;
        HAL_GPIO_WritePin(ERROR_LED_PORT, ERROR_LED_PIN, GPIO_PIN_SET);
    }

    /* DSHOT — motor UART handles
     * BUG FIX #PINS: huart7 removed; correct array is:
     *   [0]=huart4(PA0), [1]=huart5(PC12), [2]=huart3(PB10), [3]=huart6(PC6) */
    UART_HandleTypeDef* motorUarts[4] = { &huart4, &huart5, &huart3, &huart6 };
    Drivers::DShot::init(motorUarts);

    /* CRSF RX interrupt on USART2 */
    __HAL_UART_ENABLE_IT(&huart2, UART_IT_RXNE);

    /* IMU DRDY on EXTI4 (PC4, pin 24) */
    HAL_NVIC_SetPriority(IMU_DRDY_IRQn, 5, 0);
    HAL_NVIC_EnableIRQ(IMU_DRDY_IRQn);

    /* ---- Create RTOS tasks --------------------------------- */
    const osThreadAttr_t ctrlAttr  = {"CtrlLoop",0,nullptr,0,nullptr,STACK_CTRL_LOOP*4,nullptr,osPriorityRealtime,0};
    const osThreadAttr_t safeAttr  = {"Safety",  0,nullptr,0,nullptr,STACK_SAFETY*4,   nullptr,osPriorityHigh,0};
    const osThreadAttr_t crsfAttr  = {"CRSF",    0,nullptr,0,nullptr,STACK_CRSF*4,     nullptr,osPriorityAboveNormal,0};
    const osThreadAttr_t baroAttr  = {"Baro",    0,nullptr,0,nullptr,STACK_BARO*4,     nullptr,osPriorityNormal,0};
    const osThreadAttr_t magAttr   = {"Mag",     0,nullptr,0,nullptr,STACK_MAG*4,      nullptr,osPriorityNormal,0};
    const osThreadAttr_t gpsAttr   = {"GPS",     0,nullptr,0,nullptr,STACK_GPS*4,      nullptr,osPriorityNormal,0};
    const osThreadAttr_t mavAttr   = {"MAVLink", 0,nullptr,0,nullptr,STACK_MAVLINK*4,  nullptr,osPriorityLow,0};
    const osThreadAttr_t logAttr   = {"Logger",  0,nullptr,0,nullptr,STACK_LOGGER*4,   nullptr,osPriorityIdle,0};

    osThreadNew(ControlLoopTask,  nullptr,   &ctrlAttr);
    osThreadNew(SafetyTaskEntry,  &g_safety, &safeAttr);
    osThreadNew(CRSFTask,         nullptr,   &crsfAttr);
    osThreadNew(BaroTask,         nullptr,   &baroAttr);
    osThreadNew(MagTask,          nullptr,   &magAttr);
    osThreadNew(GPSTask,          nullptr,   &gpsAttr);
    osThreadNew(MAVLinkTask,      nullptr,   &mavAttr);
    osThreadNew(LoggerTask,       nullptr,   &logAttr);
}

