/* ============================================================
 *  system_init.cpp
 *
 *  BUG FIX #5: System_Init was truncated. Mutexes, semaphores,
 *  and all RTOS primitives were never created, meaning the first
 *  osMutexAcquire() would hard-fault. Fully rewritten here.
 *
 *  BUG FIX #6: mavTxMutex was used for debug UART in the original
 *  safety.c, creating a race between the safety monitor and the
 *  MAVLink task. MAVLink now uses USB CDC (separate, non-shared
 *  path). USART3 is freed for Motor 3 half-duplex DSHOT.
 *
 *  BUG FIX #7: SD card was opened/closed on every log write,
 *  causing ~100 ms FatFS seek-and-flush latency per entry.
 *  LoggerTask now opens the file once at startup and flushes
 *  on a timer (LOG_SD_FLUSH_MS = 500 ms).
 *
 *  BUG FIX #PINS (UART7 → USART3):
 *  Motor 4 was previously assigned to UART7. UART7 pins are on
 *  Port E (PE7/PE8), not accessible in LQFP64. Motor 4 is now
 *  on USART6 (PC6). USART3 (PB10) is Motor 3.
 *
 *  TASK SCHEDULE:
 *  ┌──────────────────┬──────────┬──────────┬─────────────┐
 *  │ Task             │ Rate     │ Stack(W) │ Priority    │
 *  ├──────────────────┼──────────┼──────────┼─────────────┤
 *  │ ControlLoop      │ ~3840 Hz*│ 768      │ Realtime    │
 *  │ SafetyMonitor    │ 100 Hz   │ 256      │ High        │
 *  │ CRSFTask         │ ~500 Hz  │ 256      │ AboveNormal │
 *  │ BaroTask         │ 50 Hz    │ 256      │ Normal      │
 *  │ MagTask          │ 100 Hz   │ 384      │ Normal      │
 *  │ GPSTask          │ 10 Hz    │ 384      │ Normal      │
 *  │ MAVLinkTask      │ 10 Hz    │ 512      │ Low         │
 *  │ LoggerTask       │ queue    │ 512      │ Idle+1      │
 *  └──────────────────┴──────────┴──────────┴─────────────┘
 *  * ControlLoop blocks on imuDrdySem; timing is hardware-driven.
 * ============================================================ */

